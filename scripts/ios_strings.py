#!/usr/bin/env python3
"""Generate iOS translations from the Android ones, so translators edit one set of files.

  app/src/main/res/values[-xx]/strings.xml  ->  ios/GuitarNest/Resources/<xx>.lproj/Localizable.strings
                                                + Localizable.stringsdict (plurals)
Usage: python3 scripts/ios_strings.py
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
OUT = ROOT / "ios/GuitarNest/Resources"
# Plurals whose count is not the first argument.
COUNT_ARG = {"reading_description": 2}


def android_unescape(text):
    text = "".join(text) if not isinstance(text, str) else text
    return (text.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n")
            .replace("\\@", "@").replace("\\?", "?").replace("\\\\", "\\"))


def to_ios_placeholders(text, formatted=True):
    if not formatted:
        return text
    text = re.sub(r"%(\d+\$)?s", lambda m: "%" + (m.group(1) or "") + "@", text)
    return text


def strings_escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def locale_name(folder):
    if folder == "values":
        return "en"
    code = folder.removeprefix("values-")
    return code.replace("-r", "-")


count = 0
for xml in sorted(RES.glob("values*/strings.xml")):
    root = ET.parse(xml).getroot()
    lproj = OUT / f"{locale_name(xml.parent.name)}.lproj"
    lproj.mkdir(parents=True, exist_ok=True)

    lines = ["/* Generated by scripts/ios_strings.py from the Android strings. Do not edit. */"]
    for el in root.findall("string"):
        text = android_unescape("".join(el.itertext()))
        text = to_ios_placeholders(text, el.get("formatted") != "false")
        lines.append(f'"{el.get("name")}" = "{strings_escape(text)}";')
    (lproj / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")

    dict_entries = []
    for el in root.findall("plurals"):
        name = el.get("name")
        arg = COUNT_ARG.get(name, 1)
        variants = "".join(
            f"<key>{i.get('quantity')}</key><string>{escape(to_ios_placeholders(android_unescape(''.join(i.itertext()))))}</string>"
            for i in el.findall("item")
        )
        dict_entries.append(
            f"<key>{name}</key><dict>"
            f"<key>NSStringLocalizedFormatKey</key><string>%{arg}$#@n@</string>"
            f"<key>n</key><dict><key>NSStringFormatSpecTypeKey</key><string>NSStringPluralRuleType</string>"
            f"<key>NSStringFormatValueTypeKey</key><string>d</string>{variants}</dict></dict>"
        )
    plist = ('<?xml version="1.0" encoding="UTF-8"?>\n'
             '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
             '<plist version="1.0"><dict>' + "".join(dict_entries) + "</dict></plist>\n")
    (lproj / "Localizable.stringsdict").write_text(plist, encoding="utf-8")
    count += 1

print(f"Wrote iOS strings for {count} languages to {OUT.relative_to(ROOT)}")
