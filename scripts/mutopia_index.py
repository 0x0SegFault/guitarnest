#!/usr/bin/env python3
"""Build the index of free guitar scores from the Mutopia Project (https://www.mutopiaproject.org).

Output: shared/src/commonMain/kotlin/app/guitarnest/scores/MutopiaData.kt
The app searches this index on the phone. It downloads a score only when the player taps it.

Kept: pieces for guitar, in the public domain or under a Creative Commons licence, with one MIDI file.
Usage: python3 scripts/mutopia_index.py   (needs internet; about 10 minutes)
"""
import json
import re
import sys
import time
import urllib.request

REPO = "MutopiaProject/MutopiaProject"
RAW = f"https://raw.githubusercontent.com/{REPO}/master/"
SITE = "https://www.mutopiaproject.org/"
AGENT = "GuitarNest-index (https://github.com/0x0SegFault/guitarnest)"
OUT = "shared/src/commonMain/kotlin/app/guitarnest/scores/MutopiaData.kt"
FIELDS = ["title", "composer", "opus", "date", "style", "license", "mutopiainstrument", "footer"]


def get(url, method="GET"):
    req = urllib.request.Request(url, method=method, headers={"User-Agent": AGENT})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.status, (r.read() if method == "GET" else b"")


def header(text):
    out = {}
    for f in FIELDS:
        m = re.search(r'^\s*' + f + r'\s*=\s*"((?:[^"\\]|\\.)*)"', text, re.M)
        if m:
            out[f] = m.group(1).replace('\\"', '"').strip()
    return out


NAMES = {"F. Sor": "Fernando Sor", "D. Aguado": "Dionisio Aguado", "Mateo Carcassi": "Matteo Carcassi",
         "M. Giuliani": "Mauro Giuliani", "F. Carulli": "Ferdinando Carulli", "J. Brahms": "Johannes Brahms",
         "F. Tarrega": "Francisco Tárrega", "Ludvig van Beethoven": "Ludwig van Beethoven"}


def composer_name(text):
    """One spelling per composer: no years in brackets, full first name."""
    name = re.sub(r"\s*\([^)]*\d{4}[^)]*\)", "", text).strip()
    return NAMES.get(name, name)


def licence(text):
    t = text.lower()
    if "public domain" in t:
        return "Public domain"
    m = re.search(r"creative commons (attribution[\w\s-]*?)(\d\.\d)", t)
    if m:
        kind = m.group(1).strip()
        code = "CC BY" + ("-SA" if "share" in kind else "") + ("-NC" if "noncommercial" in kind or "non-commercial" in kind else "")
        return f"{code} {m.group(2)}"
    return None


def main():
    status, body = get(f"https://api.github.com/repos/{REPO}/git/trees/master?recursive=1")
    tree = json.loads(body)["tree"]
    ly = [t["path"] for t in tree if t["type"] == "blob" and t["path"].startswith("ftp/") and t["path"].endswith(".ly")]
    # One piece per folder: the .ly named after the folder holds the header.
    folders = {}
    for p in ly:
        folder, name = p.rsplit("/", 1)
        if name[:-3] == folder.rsplit("/", 1)[1] or folder not in folders:
            folders[folder] = p
    pieces = []
    for i, (folder, path) in enumerate(sorted(folders.items())):
        try:
            text = get(RAW + path)[1].decode("utf-8", "replace")
        except Exception as e:
            print("skip (read)", path, e, file=sys.stderr)
            continue
        h = header(text)
        if "guitar" not in h.get("mutopiainstrument", "").lower():
            continue
        lic = licence(h.get("license", ""))
        if not lic or "-NC" in lic:
            continue
        name = folder.rsplit("/", 1)[1]
        midi = f"{folder}/{name}.mid"
        try:
            code = get(SITE + midi, "HEAD")[0]
        except Exception:
            code = 0
        if code != 200:
            print("skip (no single MIDI)", folder, file=sys.stderr)
            continue
        piece_id = (re.search(r"-(\d+)\s*$", h.get("footer", "")) or [None, ""])[1]
        pieces.append([h.get("title", name), composer_name(h.get("composer", "")), h.get("opus", ""), h.get("date", ""),
                       h.get("style", ""), lic, midi, piece_id])
        print(len(pieces), h.get("composer", ""), "-", h.get("title", ""), file=sys.stderr)
        time.sleep(0.3)
    write(pieces)


def esc(s):
    return s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$").replace("\t", " ").replace("\n", " ")


def write(pieces):
    rows = ["\t".join(esc(x) for x in p) for p in pieces]
    # JVM string constants are limited to 64 KB: split the rows into chunks.
    chunks, cur = [], []
    for r in rows:
        if sum(len(x) + 1 for x in cur) + len(r) > 30000:
            chunks.append(cur)
            cur = []
        cur.append(r)
    if cur:
        chunks.append(cur)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/mutopia_index.py from the Mutopia Project catalogue. Do not edit.\n")
        f.write("package app.guitarnest.scores\n\n")
        f.write("/** Tab-separated: title, composer, opus, date, style, licence, MIDI path, Mutopia id. */\n")
        f.write("internal object MutopiaData {\n")
        f.write(f"    const val COUNT = {len(pieces)}\n")
        f.write("    val CHUNKS: List<String> = listOf(\n")
        for c in chunks:
            f.write('        "' + "\\n".join(c) + '",\n')
        f.write("    )\n}\n")
    print(f"{len(pieces)} pieces written to {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
