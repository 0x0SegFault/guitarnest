            0.1 * sin(2 * PI * (330 + 44 * floor(t.mod(4.0))) * t) * exp(-3 * t.mod(0.5))
        (Math.round(x * 32768).coerceIn(-32768, 32767) / 32768.0).toFloat()
    }

